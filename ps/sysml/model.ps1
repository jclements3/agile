}
function CodeOnly([string]$t) {                                   # comments and string contents removed, line structure kept
    $t = ReplaceEach $t '/\*.*?\*/' 's' { param($m) $v = $m.Value; "`n" * ($v.Length - $v.Replace("`n", '').Length) }
    $t = (Rx '//[^\n]*').Replace($t, '')
    (Rx '"[^"\n]*"').Replace($t, '""')
}
function Mask([string]$t) {                                       # same length; comments and string contents blanked
    $t = ReplaceEach $t '/\*.*?\*/' 's' { param($m) (Rx '[^\n]').Replace($m.Value, ' ') }
    $t = ReplaceEach $t '//[^\n]*' '' { param($m) ' ' * $m.Length }
    ReplaceEach $t '"[^"\n]*"' '' { param($m) '"' + (' ' * ($m.Length - 2)) + '"' }
}
