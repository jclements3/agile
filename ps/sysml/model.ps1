$script:MEMBER_KW = '^\s*(?:(?:abstract|individual|private|public|protected)\s+)*(?:part|item|port|interface|attribute|enum|action|state|calc|constraint|requirement|verification|analysis|use\s+case|metadata|package|view|viewpoint|allocation|satisfy|allocate|concern|occurrence|connection|flow|alias)\b'
function Outline {
    $bad = @()
    $chk = { param($where, $what, $n, $file, $line) if ($n -and ($n -lt $script:MIN -or $n -gt $script:MAX)) { $script:OBAD += , @($where, $what, $n, $file, $line) } }
    $script:OBAD = @()
    foreach ($n in (SortStr @($script:DEFS.Keys))) {
        $d = $script:DEFS[$n]
        $what = if ($d.kind -ceq 'part') { "part def ${n}: parts" } else { "$($d.kind) def ${n}: sub-functions" }
        & $chk (Rel $d.file) $what (Children $n).Count $d.file $d.line
    }
    $rules = @(
        @("\bpackage\s+('[^']+'|\w+)\s*\{", 'package %s: members', 'pkg'),
        @("\brequirement\s+(?:<'[^']+'>\s*)?(\w+)[^{;]*\{", 'requirement %s: sub-requirements', 'req'),
        @('\bstate\s+def\s+(\w+)[^{;]*\{', 'state def %s: states', 'state'),
        @('\benum\s+def\s+(\w+)[^{;]*\{', 'enum def %s: literals', 'enum'))
    foreach ($f in $script:FILES) {
        $t = $script:CODES[$f]
        foreach ($r in $rules) {
            foreach ($m in (MS $t $r[0])) {
                $name = $m.Groups[1].Value; $line = 1 + (NlCount $t $m.Index)
                $flat = (Block $t ($m.Index + $m.Length - 1))[1]
                $cnt = switch ($r[2]) {
                    'pkg' { CountM $flat $script:MEMBER_KW 'm' }
                    'req' { CountM $flat '^\s*requirement\b' 'm' }
                    'state' { CountM $flat '^\s*state\b' 'm' }
                    'enum' { CountM $flat "\benum\s+'?\w" }
                }
                & $chk (Rel $f) ($r[1].Replace('%s', $name)) $cnt $f $line
            }
        }
    }
    $dirs = @($script:MODEL) + @(foreach ($d in @(Get-ChildItem -LiteralPath $script:MODEL -Recurse -Directory)) { FwdSlash $d.FullName })
    foreach ($d in (SortStr $dirs)) {
        $e = @(Get-ChildItem -LiteralPath $d -Force | Where-Object { $_.Name -cnotmatch '^\.' }).Count
        $first = $null
        foreach ($x in $script:FILES) { if ($x.StartsWith("$d/") -and $x.Substring($d.Length + 1) -cnotmatch '/') { $first = $x; break } }
        if ($null -eq $first) { foreach ($x in $script:FILES) { if ($x.StartsWith("$d/")) { $first = $x; break } } }
        & $chk ((Rel $d) + '/') 'directory entries' $e $(if ($null -ne $first) { $first } else { $d }) 1
    }
    , $script:OBAD
}
