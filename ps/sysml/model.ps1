function CmdLint {
    ParseVerbs
    $lib = LibraryNames
    $declared = NewH
    $noGrammar = $false; foreach ($a in $script:ARGS2) { if ($a -ceq '--no-grammar') { $noGrammar = $true } }
    $diags = if ($noGrammar) { @() } else { @(GrammarDiags) }
    foreach ($f in $script:FILES) {
        $t = $script:MASKS[$f]
        foreach ($m in (MS $t '\b(?:def|package)\s+(?:<[^>]*>\s*)?(\w+)')) { $declared[$m.Groups[1].Value] = 1 }
        foreach ($m in (MS $t '\battribute\s+<[^>]*>\s*(\w+)')) { $declared[$m.Groups[1].Value] = 1 }
    }
    $known = { param($x) $n = (SplitKeep $x '::'); $n = if ($n.Count) { $n[$n.Count - 1] } else { '' }; $n = $n -creplace "^'|'$", ''; $declared.ContainsKey($n) -or $lib.ContainsKey($n) }
    $pairs = @{ '}' = '{'; ')' = '('; ']' = '[' }
    foreach ($f in $script:FILES) {
        $t = $script:MASKS[$f]
        $stack = @()
        foreach ($m in (MS $t '([{}()\[\]])')) {
            $c = $m.Groups[1].Value; $p = $m.Index
            if ('{(['.Contains($c)) { $stack += , @($c, $p); continue }
            $want = $pairs[$c]
            if (-not $stack.Count -or $stack[$stack.Count - 1][0] -cne $want) { $diags += (Diag $f $p 'error' "unmatched '$c'"); break }
            $stack = @(for ($i = 0; $i -lt $stack.Count - 1; $i++) { , $stack[$i] })
        }
        foreach ($s in $stack) { $diags += (Diag $f $s[1] 'error' "'$($s[0])' is never closed") }
        foreach ($m in (MS $t "\b(?:part|item|attribute|port|calc|action|state|requirement|interface|connection|allocation|view|viewpoint|metadata|occurrence|constraint|analysis|verification|package|enum|in|out|inout|then|def|ref)\s+(?:<'[^']*'>\s*)?([A-Za-z_]\w*)\s*[:;{=\[]")) {
            $w = $m.Groups[1].Value
            if ($script:KEYWORD.ContainsKey($w)) { $diags += (Diag $f $m.Groups[1].Index 'error' "'$w' is a SysML keyword and cannot be a name (rename it, or quote it as '$w')") }
        }
        foreach ($m in (MS $t "(?<!:):(?![:>=])\s*~?((?:[A-Za-z_]\w*|'[^']+')(?:::(?:[A-Za-z_]\w*|'[^']+'))*)")) {
            if (-not (& $known $m.Groups[1].Value)) { $diags += (Diag $f $m.Groups[1].Index 'error' "unresolved type '$($m.Groups[1].Value)'") }
        }
        foreach ($m in (MS $t '\bdef\s+\w+\s*:>\s*([\w:]+)')) {
            if (-not (& $known $m.Groups[1].Value)) { $diags += (Diag $f $m.Groups[1].Index 'error' "unresolved supertype '$($m.Groups[1].Value)'") }
        }
        foreach ($m in (MS $t "\bimport\s+((?:[\w']+)(?:::[\w']+)*?)(?:::\*\*?)?\s*;")) {
            $imp = $m.Groups[1].Value; $at = $m.Groups[1].Index
            foreach ($seg in (SplitKeep $imp '::')) {
                if (& $known $seg) { continue }
                $diags += (Diag $f $at 'error' "import of unknown package '$seg'"); break
            }
        }
        foreach ($m in (MS $t '\bpackage\s+(\w+)\s*\{')) {
            $pkg = $m.Groups[1].Value; $open = $m.Index + $m.Length - 1
            $flat = (Block $t $open)[1]
            $seen = NewH
            foreach ($q in (MS $flat "^\s*(?:(?:abstract|individual|private|public)\s+)*(?:part|item|port|interface|attribute|enum|action|state|calc|constraint|requirement|verification|analysis|metadata|package|view|viewpoint|allocation|occurrence|connection)\s+(?:def\s+)?(?:<'[^']*'>\s*)?(\w+)" 'm')) {
                $nm = $q.Groups[1].Value
                $c = $seen[$nm]; $seen[$nm] = 1 + [int]$c
                if ($c -and $nm -cne 'def') { $diags += (Diag $f $open 'error' "package ${pkg}: duplicate member '$nm'") }
            }
        }
        foreach ($m in (MS $t '\b(?:calc|action)\s+(\w+)\s*:\s*([\w:]+)\s*\{')) {
            $u = $m.Groups[1].Value; $ty = LastSeg $m.Groups[2].Value; $open = $m.Index + $m.Length - 1
            $v = $script:VERBS[$ty]
            if ($null -eq $v) { continue }
            $own = NewH; foreach ($p in $v.params) { $own[$p[0]] = 1 }
            $body = $t.Substring($open, (CloseOf $t $open) - $open)
            foreach ($q in (MS $body '\bin\s+(\w+)\s*=\s*([^;]+);')) {
                $pn = $q.Groups[1].Value; $expr = $q.Groups[2].Value; $at = $open + $q.Groups[2].Index
                foreach ($z in (MS $expr '(?<![\w.:])([A-Za-z_]\w*)\b(?!\s*::)')) {
                    $w = $z.Groups[1].Value
                    if (-not $own.ContainsKey($w)) { continue }
                    $diags += (Diag $f $at 'warning' "in '$u : $ty', '$w' in the binding of '$pn' means ${ty}'s own parameter '$w'; qualify it (Parent::$w)")
                }
            }
        }
    }
    $u = NewH
    $diags = @(foreach ($d in $diags) { if (-not $u.ContainsKey($d)) { $u[$d] = 1; $d } })
    foreach ($d in $diags) { P "$d`n" }
    $errors = @($diags | Where-Object { $_ -cmatch ': error: ' }).Count
    $warnings = @($diags | Where-Object { $_ -cmatch ': warning: ' }).Count
    P "lint: $($script:FILES.Count) file(s), $errors error(s), $warnings warning(s)`n"
    $elements = 0
    foreach ($f in $script:FILES) { $elements += CountM $script:RAWS[$f] '^\s*(?:part|port|interface|connection|action|item)(?: def)?\b' 'm' }
    P "elements=$elements errors=$errors warnings=$warnings`n"
    if ($errors) { 1 } else { 0 }
}

