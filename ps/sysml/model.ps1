        $cands = @(foreach ($c in $un.ToCharArray()) { ([string]$c).ToUpper() }) + @(foreach ($c in 65..90) { [string][char]$c })
        $l = $null; foreach ($c in $cands) { if (-not $used.ContainsKey($c)) { $l = $c; break } }
        $script:STEP_LETTER[$un] = $l
        $used[$l] = 1
    }
}
function ActivityPorts([string]$type, $bind, $parentFlows, $siblings, $implicit) {   # @(ports, flows)
    if ($null -eq $implicit) { $implicit = NewH }
    $v = $script:VERBS[$type]
    if ($null -eq $v) { return , @(@(), (NewH)) }
    $ports = @(); $seen = NewH; $flows = NewH
    foreach ($p in $v.params) {
        $pn = $p[0]; $pt = $p[1]; $many = $p[2]; $dflt = $p[3]
        $expr = $bind[$pn]
        $names = @()
        if ($null -ne $expr) {
            $e = $expr
            while ($true) {
                $q = M $e '\b(?:\w+::)?(\w+)\.result\b'
                if (-not $q.Success) { break }
                $e = $e.Substring(0, $q.Index) + $e.Substring($q.Index + $q.Length)
                $sv = $siblings[$q.Groups[1].Value]
                if ($sv) { $names += $sv }
            }
            foreach ($q in (MS $e '\b(?:\w+::)?(\w+)(?:\.(\w+))?')) {
                $id = $q.Groups[1].Value
                if (-not $parentFlows.ContainsKey($id)) { continue }
                $pf = $parentFlows[$id]
                if ($pf -is [hashtable]) { $fld = if ($q.Groups[2].Success) { $q.Groups[2].Value } else { '' }; $x = $pf[$fld]; if ($null -ne $x) { $names += $x } }
                else { $names += $pf }
            }
        } elseif ($null -ne $implicit[$pn]) { $names += $implicit[$pn] }
        else { $names += $(if ($dflt) { Words $pn } else { TypeFlow $pt $many }) }
        $tag = if (($dflt -and $null -eq $expr) -or $script:CONTROL_TYPES.ContainsKey($pt)) { 'c' } else { 'i' }
        $flows[$pn] = if ($names.Count) { $names[0] } else { TypeFlow $pt $many }
        foreach ($n in $names) { if (-not $seen.ContainsKey("$tag$n")) { $seen["$tag$n"] = 1; $ports += , @($tag, $n) } }
    }
    , @($ports, $flows)
}
function PortLines([string]$pad, $ports, [string]$out, $mech, $links) {
    if ($null -eq $links) { $links = NewH }
    $lk = { param($k) if ($links.ContainsKey($k)) { ' ' + $links[$k] } else { '' } }
    $o = @()
    foreach ($p in $ports) { if ($p[0] -ceq 'i') { $o += "${pad}i# $($p[1])" + (& $lk "in $($p[1])") } }
    foreach ($p in $ports) { if ($p[0] -ceq 'c') { $o += "${pad}c# $($p[1])" + (& $lk "in $($p[1])") } }
    $o += "${pad}o# $out" + (& $lk "out $out")
    foreach ($m in $mech) { $o += "${pad}m# $m" }
    , $o
}
function DocLines([string]$pad, $v) { $d = if ($null -ne $v.doc) { $v.doc } else { '' }; WrapDoc $d "$pad## " 88 }
function Idef0Lines([string]$usage, [string]$type, $bind, $parentFlows, $siblings, [string]$path, $mech, [int]$indent, $links, $implicit) {
    $v = $script:VERBS[$type]
    if ($null -eq $v) { return , @() }
    $pad = '  ' * $indent
    $al = Allocations
    $mc = $al[$path]; if ($null -eq $mc) { $mc = $al["def:$type"] }; if ($null -eq $mc) { $mc = $mech }
    $pf = ActivityPorts $type $bind $parentFlows $siblings $implicit
    $outn = $siblings[$usage]; if ($null -eq $outn) { $outn = OutName $usage $type }
    $o = @("${pad}a# " + (PlainName $type)) + (DocLines "$pad  " $v) + (PortLines "$pad  " $pf[0] $outn $mc $links)
    $sib = SiblingNames $type
    $imp = ImplicitFlows $type $sib
    foreach ($u in $v.uses) { $o += (Idef0Lines $u[0] $u[1] $u[2] $pf[1] $sib "$path.$($u[0])" $mc ($indent + 1) $null $imp[$u[0]]) }
    , $o
}
function RunIdef0($a) {                                             # idef0.ps1 in-process: @(stdout text, exit code)
    $tmpf = Join-Path $env:TEMP ('model-idef0-' + [string](Get-Random) + '.out')
    $tool = Join-Path $PSScriptRoot '..\idef0\idef0.ps1'
    & $tool @a --out $tmpf
    $rc = $LASTEXITCODE
    $t = ''; if (Test-Path -LiteralPath $tmpf) { $t = SL_ReadKeep $tmpf; Remove-Item -LiteralPath $tmpf }
    , @($t, $rc)
}
function CmdIdef0([bool]$fromDocs = $false) {
    ParseVerbs
    $rootV = $script:VERBS[$script:VERB_ROOT]
    if ($fromDocs -and -not $script:CONF.ContainsKey('verb_root') -and -not ($null -ne $rootV -and @($rootV.uses).Count)) {
        P "idef0: skipped: sysml.conf sets no verb_root (set it to the top action def to get docs/idef0/)`n"
        return 0
    }
    StepLetters
    $dir = "$($script:ROOT)/docs/idef0"
    foreach ($d in @("$($script:ROOT)/docs", $dir)) { if (-not (Test-Path -LiteralPath $d)) { $null = New-Item -ItemType Directory -Path $d } }
    $md = "$dir/$($script:IDEF0_NAME).md"
    if ($null -eq $rootV) { Flush; PErr "idef0: no calc def or action def named '$($script:VERB_ROOT)' (verb_root in sysml.conf)"; return 1 }
    $inType = if (@($rootV.params).Count) { $rootV.params[0][1] } else { $null }
    $rec = NewH
    if ($null -ne $inType) {
        foreach ($f in $script:FILES) {
            $t = $script:CODES[$f]
            $st = $script:CPOS[$f]; if ($null -eq $st) { $st = 0 }
            $q = (Rx ('\bitem\s+def\s+' + (Esc $inType) + '\s*\{')).Match($t, $st)
            if (-not $q.Success) { $script:CPOS[$f] = $null; continue }
            $script:CPOS[$f] = $q.Index + $q.Length
            $flat = (Block $t ($q.Index + $q.Length - 1))[1]
            foreach ($z in (MS $flat '\b(?:item|attribute)\s+(\w+)\s*:\s*([\w:]+)\s*(\[[^\]]*\])?')) {
                $rec[$z.Groups[1].Value] = TypeFlow (LastSeg $z.Groups[2].Value) $(if ($z.Groups[3].Value.Contains('*')) { 1 } else { 0 })
            }
        }
    }
    $rootFlows = NewH; foreach ($p in $rootV.params) { $rootFlows[$p[0]] = $rec }
    $rootSib = SiblingNames $script:VERB_ROOT
    $alloc = Allocations
    $steps = @($rootV.uses)
    $mode = ConfGet 'idef0_models' 'auto'
    if ($mode -cnotmatch '^(auto|steps|root)\z') { Flush; PErr "idef0: idef0_models in sysml.conf is auto, steps or root, not '$mode'"; return 2 }
    if ($mode -ceq 'auto') { $mode = 'root'; foreach ($s in $steps) { $vs = $script:VERBS[$s[1]]; if ($null -ne $vs -and @($vs.uses).Count) { $mode = 'steps'; break } } }
    if (-not $steps.Count) { Flush; PErr "idef0: $($script:VERB_ROOT) has no steps (action or calc usages) to draw; give it some, or set verb_root in sysml.conf"; return 1 }
    $rimp = ImplicitFlows $script:VERB_ROOT $rootSib
    $ports = NewH; $flows = NewH; $producerOf = NewH
    foreach ($u in $steps) {
        $pf = ActivityPorts $u[1] $u[2] $rootFlows $rootSib $rimp[$u[0]]
        $ports[$u[0]] = $pf[0]; $flows[$u[0]] = $pf[1]
        $producerOf[$rootSib[$u[0]]] = $u[0]
    }
    $step = NewH; foreach ($u in $steps) { $step[$u[0]] = $u }
    $alinks = NewH; $firstConsumer = NewH
    foreach ($u in $steps) {
        $bn = $u[0]; $bt = $u[1]; $bb = $u[2]
        $vb = $script:VERBS[$bt]
        foreach ($p in $vb.params) {
            $pn = $p[0]
            $bx = if ($null -ne $bb[$pn]) { $bb[$pn] } else { '' }
            $an = $null
            foreach ($q in (MS $bx '\b(\w+)\.result\b')) { $c = $q.Groups[1].Value; if ($step.ContainsKey($c) -and $c -cne $bn) { $an = $c; break } }
            if (-not $an) { continue }
            $at = $step[$an][1]
            $va = $script:VERBS[$at]
            $rex = if ($null -ne $va.return_expr) { $va.return_expr } else { '' }
            $pm = M $rex '\b(\w+)\.result\b'
            if (-not $pm.Success) { continue }
            $prod = $pm.Groups[1].Value
            $pu = $null; foreach ($x in $va.uses) { if ($x[0] -ceq $prod) { $pu = $x; break } }
            $flow = $rootSib[$an]
            foreach ($c in $vb.uses) {
                $hit = $false
                foreach ($val in $c[2].Values) { if ((M $val ('(?<![\w.])(?:\w+::)?' + (Esc $pn) + '\b(?!\.result)')).Success) { $hit = $true; break } }
                if (-not $hit) { continue }
                if (-not $alinks.ContainsKey($bn)) { $alinks[$bn] = NewH }
                if (-not $alinks[$bn].ContainsKey($c[0])) { $alinks[$bn][$c[0]] = NewH }
                $alinks[$bn][$c[0]]["in $flow"] = "< $($script:STEP_LETTER[$an])|" + (PlainName $pu[1]) + "|$flow"
                if (-not $firstConsumer.ContainsKey($an)) { $firstConsumer[$an] = @($bn, $c) }
            }
            $fcv = $firstConsumer[$an]
            if ($null -ne $fcv) {
                $fb = $fcv[0]; $fcu = $fcv[1]
                if (-not $alinks.ContainsKey($an)) { $alinks[$an] = NewH }
                if (-not $alinks[$an].ContainsKey($prod)) { $alinks[$an][$prod] = NewH }
                if (-not $alinks[$an][$prod].ContainsKey("out $flow")) { $alinks[$an][$prod]["out $flow"] = "> $($script:STEP_LETTER[$fb])|" + (PlainName $fcu[1]) + "|$flow" }
            }
        }
    }
    $ED = $script:EMDASH; $ML = $script:MODEL_LETTER; $VR = $script:VERB_ROOT; $TT = $script:TITLE
    $rootFile = RelRoot $script:DEFS[$VR].file
    $mdl = @("<!-- Generated by: $($script:ME) idef0 -- do not edit by hand.",
        "     Source of truth: the verb tree under $VR ($rootFile) and its allocate statements.",
        '     Build (from the agile kit root):',
        "             perl tools/idef0/idef0.pl lint $($script:IDEF0_NAME).md",
        "             perl tools/idef0/idef0.pl html $($script:IDEF0_NAME).md > plates.html",
        "             perl tools/idef0/idef0.pl links $($script:IDEF0_NAME).md > INTERFACES -->", '',
        ("# $TT " + (Words $script:IDEF0_NAME) + " $ED IDEF0 model set"), '')
    if ($mode -ceq 'steps') {
        $mdl += @("The $TT verbs drawn as IDEF0 plates: one model per top-level step of $VR, so each step", 'can be owned by one team. Every box is a function from `model/`; a box is decomposed')
    } else {
        $mdl += @("The $TT verbs drawn as IDEF0 plates: one model, $VR, whose top-level steps are the boxes of", "plate ${ML}0 (its context, the whole function as one box, is plate $ML-0). Every box is a function from ``model/``; a box is decomposed")
    }
    $mdl += @('on its own plate when the function is composed of smaller functions (2 to 9 per plate).', '',
        '- **Inputs** (left): the data a function transforms, named after the flow wired into it.',
        '- **Controls** (top): orders, authorizations and rules (the `control_types` of `sysml.conf`),',
        '  plus policy constants (parameters with default values, such as thresholds).',
        '- **Output** (right): the one result the function returns.',
        "- **Mechanism** (bottom): the part (noun) that performs the function, from the model's",
        "  ``allocate`` statements; a function without its own allocation inherits its parent's.",
        "- **Model line** (``t``): the step's own inputs, controls and output (its A-0 context). Hand-offs",
        '  between steps are cross-model links (`<` comes from, `>` goes to), listed in `INTERFACES`.', '')
    if ($mode -ceq 'root') {
        $ttl = PlainName $VR
        $mech = $alloc["def:$VR"]; if ($null -eq $mech) { $mech = $alloc[''] }; if ($null -eq $mech) { $mech = @(PlainName $script:NOUN_ROOT) }
        $rports = (ActivityPorts $VR (NewH) (NewH) (NewH) $null)[0]
        $dr = $script:DEFS[$VR]
        $rout = if ($dr.returns) { TypeFlow $dr.returns $dr.many } else { Words $VR }
        $mdl += @("## Model $ML $ED $ttl", '')
        if ($rootV.doc) { $mdl += (WrapDoc $rootV.doc '' 88); $mdl += '' }
        $mdl += @(('Performed by: ' + ($mech -join ', ') + '. Inputs a step takes without an `in x = step.result` binding are fed by the nearest'), 'earlier step whose result has their type (converted v1 activities carry no object flows).', '')
        $mdl += @('```idef0', "t$ML $ttl") + (DocLines '' $rootV) + (PortLines '  ' $rports $rout $mech $null)
        foreach ($u in $steps) { $mdl += (Idef0Lines $u[0] $u[1] $u[2] $rootFlows $rootSib $u[0] $mech 1 $null $rimp[$u[0]]) }
        $mdl += @('```', '')
    }
    if ($mode -ceq 'steps') {
        foreach ($u in $steps) {
            $un = $u[0]; $ut = $u[1]
            $v = $script:VERBS[$ut]
            $lt = $script:STEP_LETTER[$un]; if ($null -eq $lt) { $lt = $un.Substring(0, 1).ToUpper() }
            $label = $script:STEP_LABEL[$un]; if ($null -eq $label) { $label = Words $un }
            $ttl = if ($label -ceq (PlainName $ut)) { $label } else { "$label $ED " + (PlainName $ut) }
            $mech = $alloc[$un]; if ($null -eq $mech) { $mech = $alloc["def:$ut"] }; if ($null -eq $mech) { $mech = $alloc[''] }; if ($null -eq $mech) { $mech = @(PlainName $script:NOUN_ROOT) }
            $in = @(foreach ($p in $ports[$un]) {
                $fl = $p[1]; $src = $null
                foreach ($s in $steps) { if ($rootSib[$s[0]] -ceq $fl -and $s[0] -cne $un) { $src = $s[0]; break } }
                $fl + $(if ($src) { " (from $($script:STEP_LETTER[$src]))" } else { '' })
            })
            $to = @(foreach ($s in $steps) { $sn = $s[0]; if ($sn -cne $un) { $hit = $false; foreach ($p in $ports[$sn]) { if ($p[1] -ceq $rootSib[$un]) { $hit = $true } }; if ($hit) { $sn } } })
            $to = SortStr $to
            $mdl += @("## Model $lt $ED $ttl", '')
            if ($v.doc) { $mdl += (WrapDoc $v.doc '' 88); $mdl += '' }
            $sp = @(foreach ($x in (Spine $ut $lt)) { if ($x[0] -cne $lt) { "$($x[0]) $($x[1])" } })
            $mdl += @(('SPINE: ' + ($sp -join ' -> ') + '.'), '')
            $team = if ($script:STEP_LABEL.ContainsKey($un)) { $script:STEP_LABEL[$un] } else { Words $un }
            $mdl += @(("Team: $team. Performed by: " + ($mech -join ', ') + '.'), '')
            $toTxt = if ($to.Count) { ' to ' + ((@(foreach ($x in $to) { "$($script:STEP_LETTER[$x]) " + $(if ($script:STEP_LABEL.ContainsKey($x)) { $script:STEP_LABEL[$x] } else { $x }) })) -join ', ') } else { '' }
            $mdl += @(('Interfaces: takes ' + ($in -join '; ') + '. Hands on ' + $rootSib[$un] + $toTxt + '.'), '')
            $sib = SiblingNames $ut
            $mdl += @('```idef0', "t$lt $ttl") + (DocLines '' $v) + (PortLines '  ' $ports[$un] $rootSib[$un] $mech $null)
            foreach ($c in $v.uses) {
                $lk = $null; if ($alinks.ContainsKey($un)) { $lk = $alinks[$un][$c[0]] }
                $mdl += (Idef0Lines $c[0] $c[1] $c[2] $flows[$un] $sib "$un.$($c[0])" $mech 1 $lk $null)
            }
            $mdl += @('```', '')
        }
    }
    WriteText $md ($mdl -join "`n")
    P ('wrote ' + (Rel $md) + "`n")
    $lint = RunIdef0 @('lint', $md)
    P $lint[0]
    $status = $lint[1]
    $save = { param($path, $text) WriteText $path $text; P ('wrote ' + (Rel $path) + "`n") }
    & $save "$dir/plates.html" (RunIdef0 @('html', $md))[0]
    & $save "$dir/INTERFACES" (RunIdef0 @('links', $md))[0]
    $svg = "$dir/svg"
    if (-not (Test-Path -LiteralPath $svg)) { $null = New-Item -ItemType Directory -Path $svg }
    Get-ChildItem -LiteralPath $svg -Filter '*.svg' -File | Remove-Item
    if ($mode -ceq 'root') {
        & $save "$svg/plate-$ML-0.svg" (RunIdef0 @('svg', "$ML-0", $md))[0]
        & $save "$svg/plate-${ML}0.svg" (RunIdef0 @('svg', "${ML}0", $md))[0]
        for ($i = 1; $i -le $steps.Count; $i++) {
            $vs = $script:VERBS[$steps[$i - 1][1]]
            if ($null -eq $vs -or -not @($vs.uses).Count) { continue }
            & $save "$svg/plate-$ML$i.svg" (RunIdef0 @('svg', "$ML$i", $md))[0]
        }
    }
    if ($mode -ceq 'steps') {
        foreach ($u in $steps) {
            $lt = $script:STEP_LETTER[$u[0]]
            $plate = (RunIdef0 @('svg', "${lt}0", $md))[0]
            if ($plate -eq '') { $plate = (RunIdef0 @('svg', "$lt-0", $md))[0] }
            & $save "$svg/plate-${lt}0.svg" $plate
        }
    }
    $old = "$dir/plate-${ML}0.svg"; if (Test-Path -LiteralPath $old) { Remove-Item -LiteralPath $old }
    $status
}

