<#
model.ps1 -- the agile kit's tools/sysml/model.pl in Windows PowerShell 5.1 (Constrained Language Mode safe):
structure checker, tree renderer and document generator for a SysML v2 text model. Same commands, same output,
same generated files (byte for byte, including the "Generated by: perl tools/sysml/model.pl" headers, so a team
can mix the Perl and PowerShell tools on one model without the docs ever looking stale).

  model.ps1 [--root DIR] COMMAND [options]      ('help' lists the commands)

What differs from model.pl, because the baseline PC has no Perl, Java or git:
  validate       needs Java and the SysML v2 Pilot: reported "not run" (exit 3). Not run is not green.
  precommit      checks generated docs against what was there before regenerating (no git staging area).
  install-hooks  needs git: not available.
  draw, plates, diff, threats, gate   run ps\sysml\views (the PowerShell port of tools/sysml/views); diff --git needs git.
  lint           the same grammar-exact syntax check as sysml.ps1 (slow in CLM: about 20 ms per token the
                 first time; unchanged files are cached in %TEMP%).
lint and sysml.ps1 are convention and syntax checkers, NOT the reference parser: the Halberd phase-2 model
passes both and fails the OMG Pilot with 47 errors (missing imports, subject-first, a name resolving to the
wrong package). --out FILE writes stdout to FILE as UTF-8 (Windows PowerShell's '>' writes UTF-16).
#>
