    $order = @(); $type = NewH
    foreach ($s in $d.super) {
        foreach ($kv in (Children $s $seen)) { if (-not $type.ContainsKey($kv[0])) { $order += $kv[0] }; $type[$kv[0]] = $kv[1] }
    }
    foreach ($kv in $d.children) { if (-not $type.ContainsKey($kv[0])) { $order += $kv[0] }; $type[$kv[0]] = $kv[1] }
    , @(foreach ($o in $order) { , @($o, $type[$o]) })
}
function LevelOf([string]$name, $seen = $null) {
