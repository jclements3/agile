function Block([string]$t, [int]$open) {                          # @(body, flat): the block whose '{' is at $open
    $n = $t.Length; $i = $open + 1; $depth = 1; $flat = @()
    $br = [char[]]@('{', '}')
    while ($depth -and $i -lt $n) {
        $j = $t.IndexOfAny($br, $i)
        if ($j -lt 0) { if ($depth -eq 1) { $flat += $t.Substring($i) }; $i = $n; break }
        if ($depth -eq 1) { $flat += $t.Substring($i, $j - $i) }
        if ($t[$j] -eq '{') { if ($depth -eq 1) { $flat += '{' }; $depth++ } else { $depth-- }
        $i = $j + 1
    }
    $len = $i - $open - 2
    $body = if ($len -ge 0) { $t.Substring($open + 1, $len) } else { '' }
    , @($body, ($flat -join ''))
}
function CloseOf([string]$t, [int]$open) {
    $n = $t.Length; $i = $open + 1; $depth = 1; $br = [char[]]@('{', '}')
    while ($depth -and $i -lt $n) {
        $j = $t.IndexOfAny($br, $i)
        if ($j -lt 0) { $i = $n; break }
        if ($t[$j] -eq '{') { $depth++ } else { $depth-- }
        $i = $j + 1
    }
    $i - 1
}
