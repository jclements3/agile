function CmdPrecommit {
    $bad = 0
    P "== lint`n"; $bad = $bad -bor (CmdLint)
    P "== check`n"; $bad = $bad -bor (Report)
    P "== docs`n"
    $before = DocsSnapshot
    $script:MUTE = $true
    try { $null = CmdDocs; $null = CmdTrace } finally { $script:MUTE = $false }
    $after = DocsSnapshot
    $stale = @(foreach ($k in (SortStr @($after.Keys))) { if (-not $before.ContainsKey($k) -or $before[$k] -cne $after[$k]) { $k } })
    if ($stale.Count) {
        P ("generated docs were out of date and have been regenerated:`n" + ((@(foreach ($s in $stale) { "$s`n" })) -join '') + "review them and hand them on with the model (no git on this PC: nothing is staged)`n")
        $bad = 1
    } else { P "docs up to date`n" }
    if ($bad) { 1 } else { 0 }
}
