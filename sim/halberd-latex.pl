  tick label style={font=\figfont}, label style={font=\figfont}, legend style={font=\figfont, draw=none, fill=none,
  at={(0.5,1.02)}, anchor=south}, every axis plot/.append style={line width=0.9pt, mark size=1.2pt}}}
