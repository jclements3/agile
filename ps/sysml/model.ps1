function ParseVerbs {
    if ($script:VERBS_DONE) { return }
    $script:VERBS_DONE = $true
    foreach ($f in $script:FILES) {
        $t = $script:CODES[$f]; $raw = $script:RAWS[$f]
        foreach ($m in (MS $t '\b(calc|action)\s+def\s+(\w+)[^{;]*\{')) {
            $kind = $m.Groups[1].Value; $name = $m.Groups[2].Value
            $bf = Block $t ($m.Index + $m.Length - 1); $body = $bf[0]; $flat = $bf[1]
            $params = @()
            foreach ($q in (MS $flat '(?:^|[;{}]|\bdoc\b)\s*(?:inout|in)\s+(?:(?:item|attribute|part|ref)\s+)?(\w+)\s*:\s*([\w:]+)\s*(\[[^\]]*\])?\s*(default)?' 'm')) {
                $mult = $q.Groups[3].Value
                $params += , @($q.Groups[1].Value, (LastSeg $q.Groups[2].Value), $(if ($mult -cmatch '\*|\.\.\s*[2-9]|\[\s*[2-9]') { 1 } else { 0 }), $(if ($q.Groups[4].Success) { 1 } else { 0 }))
            }
            $uses = @()
            foreach ($q in (MS $body ('\b' + $kind + "\s+(\w+|'[^']+')\s*:\s*([\w:]+)\s*(\{|;)"))) {
                $u = $q.Groups[1].Value -creplace "^'|'\z", ''
                $ty = LastSeg $q.Groups[2].Value
                $bind = NewH
                if ($q.Groups[3].Value -ceq '{') {
                    $bb = (Block $body ($q.Index + $q.Length - 1))[0]
                    foreach ($z in (MS $bb '\bin\s+(\w+)\s*=\s*([^;]+);')) { $bind[$z.Groups[1].Value] = $z.Groups[2].Value }
                }
                $uses += , @($u, $ty, $bind)
            }
            $doc = ''
            $dm = M $raw ('\b' + $kind + '\s+def\s+' + (Esc $name) + '\b')
            if ($dm.Success) {
                $at = $dm.Index + $dm.Length
                $head = $raw.Substring($at, [int]$(if ($raw.Length - $at -lt 1500) { $raw.Length - $at } else { 1500 }))
                $head = (Rx '\n\s*(?:in|out|return|calc|action)\b.*' 's').Replace($head, '', 1)
                $d2 = M $head 'doc\s*/\*\s*(.*?)\s*\*/' 's'
                $dd = if ($d2.Success) { $d2.Groups[1].Value } else { '' }
                $doc = (@(foreach ($l in (SplitKeep $dd "`n")) { $l -creplace '^\s*\*?\s*', '' })) -join ' '
            }
            $re = M $flat "($($script:RETURN)[^;]*;)"
            $rexpr = if ($re.Success) { $re.Groups[1].Value } else { $null }
            $script:VERBS[$name] = @{ params = $params; uses = $uses; doc = $doc; return_expr = $rexpr }
        }
    }
}
