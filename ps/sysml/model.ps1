$script:LEVEL_TAG = @($null) + @(foreach ($x in (ConfList 'level_tags')) { $x })
if ($script:LEVEL_TAG.Count -lt 2) { $script:LEVEL_TAG = @($null, 'L1Enterprise', 'L2Segment', 'L3System', 'L4Subsystem', 'L5Assembly', 'L6Subassembly', 'L7Component', 'L8Part', 'L9Piece') }
function SplitStatements([string]$text, [string]$masked) {
    $out = @(); $start = 0; $depth = 0
    for ($i = 0; $i -lt $masked.Length; $i++) {
        $c = $masked[$i]
        if ($c -eq '{') { $depth++ }
        elseif ($c -eq '}') { $depth--; if (-not $depth) { $out += $text.Substring($start, $i + 1 - $start); $start = $i + 1 } }
        elseif ($c -eq ';' -and -not $depth) { $out += $text.Substring($start, $i + 1 - $start); $start = $i + 1 }
    }
    $out += $text.Substring($start)
    , @(foreach ($x in $out) { $y = ($x -creplace '^\s+', '') -creplace '\s+$', ''; if ($y -cmatch '\S') { $y } })
}
function CmdNew {
    $a = @($script:ARGS2)
    $kind = if ($a.Count -gt 0) { $a[0] } else { $null }; $name = if ($a.Count -gt 1) { $a[1] } else { $null }
    $o = NewH
    for ($i = 2; $i -lt $a.Count; $i += 2) { $k = $a[$i] -creplace '^--', ''; $o[$k] = $(if ($i + 1 -lt $a.Count) { $a[$i + 1] } else { $null }) }
    $usageHelp = "usage: $($script:ME) new part NAME --in PARENT [--usage NAME] [--doc TEXT]`n       $($script:ME) new verb NAME --in PARENT [--usage NAME] [--takes 'x:Type,y:Type'] [--returns Type] [--doc TEXT]"
    if (-not $kind -or $kind -cnotmatch '^(part|verb)$' -or -not $name -or -not $o['in']) { Flush; PErr $usageHelp; return 2 }
    if ($name -cnotmatch '^[A-Z]\w*$') { Flush; PErr 'new: NAME must be a PascalCase identifier'; return 2 }
    if ($script:DEFS.ContainsKey($name)) { Flush; PErr ("new: '$name' already exists in " + (Rel $script:DEFS[$name].file)); return 1 }
    $parent = $script:DEFS[$o['in']]
    $want = if ($kind -ceq 'part') { 'part' } elseif ($null -ne $parent -and $parent.kind -ceq 'action') { 'action' } else { 'calc' }
    if ($null -eq $parent -or $parent.kind -cne $want) { Flush; PErr ('new: no ' + $(if ($kind -ceq 'part') { 'part def' } else { 'calc def or action def' }) + " named '$($o['in'])'"); return 1 }
    $f = $parent.file
    $raw = $script:RAWS[$f]; $mt = $script:MASKS[$f]
    $pm = M $mt ('\b' + $want + '\s+def\s+' + (Esc $o['in']) + '\b[^{;]*\{')
    if (-not $pm.Success) { Flush; PErr ("new: cannot find '$($o['in'])' in " + (Rel $f)); return 1 }
    $open = $pm.Index + $pm.Length - 1
    $close = CloseOf $mt $open
    $lineStart = $raw.LastIndexOf("`n", $open) + 1
    $indent = (M $raw.Substring($lineStart) '^([ \t]*)').Groups[1].Value
    $usage = if ($o.ContainsKey('usage')) { $o['usage'] } else { LcFirst $name }
    $doc = if ($o.ContainsKey('doc')) { $o['doc'] } else { 'TODO: describe what this ' + $(if ($kind -ceq 'part') { 'part is.' } else { 'function computes.' }) }
    if ($kind -ceq 'part') {
        $lvl = LevelOf $o['in']
        $tag = if ($lvl -and $lvl -lt 9 -and $script:LEVEL_TAG.Count -gt $lvl + 1 -and $script:LEVEL_TAG[$lvl + 1]) { "@$($script:LEVEL_TAG[$lvl + 1]); " } else { '' }
        $useLine = "$indent    part $usage : $name;`n"
        $defText = "`n$indent" + "part def $name {`n$indent    $tag`n$indent    doc /* $doc */`n$indent}`n"
        $defText = $defText -creplace ' +\n', "`n"
    } else {
        $takes = @(foreach ($x in (SplitKeep $(if ($o.ContainsKey('takes')) { $o['takes'] } else { '' }) '\s*,\s*')) { if ($x -cmatch '\S') { , @([regex]::Split($x, '\s*:\s*', 2)) } })
        $ret = if ($o.ContainsKey('returns')) { $o['returns'] } else { 'Real' }
        $useLine = "$indent    $want $usage : $name" + $(if ($takes.Count) { " {`n" + ((@(foreach ($x in $takes) { "$indent        in $($x[0]) = $($o['in'])::$($x[0]);  // TODO: bind`n" })) -join '') + "$indent    }`n" } else { ";`n" })
        $defText = "`n$indent" + "$want def $name {`n$indent    doc /* $doc */`n" + ((@(foreach ($x in $takes) { "$indent    in $($x[0]) : $($x[1]);`n" })) -join '') + "$indent    " + $(if ($want -ceq 'action') { 'out result' } else { 'return' }) + " : $ret;`n$indent}`n"
    }
    if ($raw.LastIndexOf("`n", $close) -lt $open) {
        $stmts = SplitStatements $raw.Substring($open + 1, $close - $open - 1) $mt.Substring($open + 1, $close - $open - 1)
        $expBlock = "{`n" + ((@(foreach ($s in $stmts) { "$indent    $s`n" })) -join '') + "$indent}"
        $raw = $raw.Substring(0, $open) + $expBlock + $raw.Substring($close + 1)
        $mt = Mask $raw
        $close = CloseOf $mt $open
    }
    $cle = $raw.IndexOf("`n", $close); if ($cle -lt 0) { $cle = $raw.Length }
    $cls = $raw.LastIndexOf("`n", $close) + 1
    $tailStart = $cle + 1; $mid = if ($tailStart -le $raw.Length) { $raw.Substring($cls, $tailStart - $cls) } else { $raw.Substring($cls) }
    $tail = if ($tailStart -le $raw.Length) { $raw.Substring($tailStart) } else { '' }
    $new = $raw.Substring(0, $cls) + $useLine + $mid + $defText + $tail
    WriteFileKeep $f $new
    P ("new: added $want def $name and usage '$usage' to $($o['in']) in " + (Rel $f) + "`n")
    $kids = (Children $o['in']).Count + 1
    P ("new: $($o['in']) now has $kids child(ren)" + $(if ($kids -lt $script:MIN) { ' -- add a sibling (2..9 rule)' } elseif ($kids -gt $script:MAX) { ' -- too many, group them (2..9 rule)' } else { '' }) + "`n")
    P "new: run '$($script:ME) check' and '$($script:ME) docs'`n"
    0
}
function CmdRename {
    $a = @($script:ARGS2)
    $old = if ($a.Count -gt 0) { $a[0] } else { $null }; $new = if ($a.Count -gt 1) { $a[1] } else { $null }
    $write = $a -ccontains '--write'; $any = $a -ccontains '--any'
    if (-not $old -or -not $new -or $new -cnotmatch '^[A-Za-z_]\w*$') { Flush; PErr "usage: $($script:ME) rename OLD NEW [--write] [--any]"; return 2 }
    $isDef = $false; foreach ($f in $script:FILES) { if ((M $script:MASKS[$f] ('\bdef\s+' + (Esc $old) + '\b')).Success) { $isDef = $true } }
    if (-not $isDef -and -not $any) { Flush; PErr "rename: '$old' is not a definition name (use --any to rename any identifier)"; return 1 }
    foreach ($f in $script:FILES) { if ((M $script:MASKS[$f] ('\b(?:def|package)\s+' + (Esc $new) + '\b')).Success) { Flush; PErr "rename: '$new' already exists"; return 1 } }
    if ($script:KEYWORD.ContainsKey($new)) { Flush; PErr "rename: '$new' is a SysML keyword"; return 1 }
    $total = 0
    foreach ($f in $script:FILES) {
        $n = CountM $script:RAWS[$f] ('\b' + (Esc $old) + '\b')
        if (-not $n) { continue }
        $total += $n
        P ((PadR (Rel $f) 60) + ' ' + (PadL $n 3) + "`n")
        if ($write) { WriteFileKeep $f ((Rx ('\b' + (Esc $old) + '\b')).Replace($script:RAWS[$f], $new.Replace('$', '$$'))) }
    }
    if ($write) { P "rename: $total occurrence(s) of '$old' renamed to '$new'; now run check and docs`n" } else { P "rename: $total occurrence(s) found; add --write to apply`n" }
    0
}
function CmdTags {
