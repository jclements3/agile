    WriteText $out ("!_TAG_FILE_FORMAT`t2`t//`n!_TAG_FILE_SORTED`t1`t/0=unsorted, 1=sorted/`n" + ((@(foreach ($x in $tagList) { "$x`n" })) -join ''))
    P "tags: wrote $($tagList.Count) tags to tags (in vim: Ctrl-] on a name, Ctrl-T to go back)`n"
    0
}

# ================================================================ trace
$script:RUID = 0
function CmdTrace {
    $reqs = @()
    foreach ($f in $script:FILES) {
        $t = $script:MASKS[$f]; $raw = $script:RAWS[$f]
        $found = @()
        foreach ($m in (MS $t "\brequirement\s+(?!def\b)(?:<'([^']+)'>\s*)?(\w+)[^{;]*\{")) {
            $open = $m.Index + $m.Length - 1
            $close = CloseOf $t $open
            $dm = M $raw.Substring($open, $close - $open) '\bdoorsId\s*=\s*"([^"]+)"'
            $id = if ($m.Groups[1].Success) { $m.Groups[1].Value } elseif ($dm.Success) { $dm.Groups[1].Value } else { $m.Groups[2].Value }
            $script:RUID++; $found += , @{ id = $id; name = $m.Groups[2].Value; open = $open; close = $close; file = $f; parent = $null; uid = $script:RUID }
        }
        foreach ($r in $found) {
            $par = $null
            foreach ($x in $found) { if ($x.open -lt $r.open -and $x.close -gt $r.close) { if ($null -eq $par -or $x.open -gt $par.open) { $par = $x } } }
            $r.parent = $par
            $head = $raw.Substring($r.open, $r.close - $r.open)
            $head = (Rx '\brequirement\b.*' 's').Replace($head, '', 1)
            $d2 = M $head 'doc\s*/\*\s*(.*?)\s*\*/' 's'
            $dd = if ($d2.Success) { $d2.Groups[1].Value } else { '' }
            $r.doc = (@(foreach ($l in (SplitKeep $dd "`n")) { $l -creplace '^\s*\*?\s*', '' })) -join ' '
        }
        foreach ($r in $found) {
            $p = @($r.name); $q = $r.parent
            while ($null -ne $q) { $p = @($q.name) + $p; $q = $q.parent }
            $r.path = $p -join '.'; $r.depth = $p.Count - 1
            $leaf = $true; foreach ($x in $found) { if ($null -ne $x.parent -and $x.parent.uid -eq $r.uid) { $leaf = $false } }
            $r.leaf = $leaf
            $reqs += , $r
        }
    }
    $sat = NewH; $ver = NewH
    foreach ($f in $script:FILES) {
        $t = $script:MASKS[$f]
        foreach ($m in (MS $t '\bsatisfy\s+([\w:.]+)\s+by\s+([\w.]+)\s*;')) { $k = LastSeg $m.Groups[1].Value; if (-not $sat.ContainsKey($k)) { $sat[$k] = @() }; $sat[$k] += $m.Groups[2].Value }
        foreach ($m in (MS $t '\bverification\s+def\s+(\w+)[^{;]*\{')) {
            $vname = $m.Groups[1].Value; $open = $m.Index + $m.Length - 1
            $body = $t.Substring($open, (CloseOf $t $open) - $open)
            $mm = M $script:RAWS[$f].Substring($open, $body.Length) "(?:method\s*=\s*VerificationMethod|kind\s*=\s*VerificationMethodKind)::'?(\w+)"
            $method = if ($mm.Success) { $mm.Groups[1].Value } else { $null }
            foreach ($q in (MS $body '\bverify\s+([\w:.]+)\s*;')) { $k = LastSeg $q.Groups[1].Value; if (-not $ver.ContainsKey($k)) { $ver[$k] = @() }; $ver[$k] += ($vname + $(if ($method) { " ($method)" } else { '' })) }
        }
    }
    $rows = @(); $missSat = 0; $missVer = 0
    $sorted = SortBy $reqs { param($x, $y) $r = Cmp $x.file $y.file; if ($r) { return $r }; if ($x.open -lt $y.open) { -1 } elseif ($x.open -gt $y.open) { 1 } else { 0 } }
    foreach ($r in $sorted) {
        $sp = $r.path.Split('.')
        $s = @(for ($i = 0; $i -lt $sp.Count; $i++) { $k = ($sp[0..$i]) -join '.'; if ($sat.ContainsKey($k)) { $sat[$k] } })
        $v = if ($ver.ContainsKey($r.path)) { @($ver[$r.path]) } else { @() }
        $status = if (-not $r.leaf) { 'group' } elseif (-not $s.Count) { 'not satisfied' } elseif (-not $v.Count) { 'not verified' } else { 'ok' }
        if ($script:NEED_PREFIX -ne '' -and $r.id.StartsWith($script:NEED_PREFIX)) { $status = 'need' }
        if ($status -ceq 'not satisfied') { $missSat++ }
        if ($status -ceq 'not verified') { $missVer++ }
        $txt = $r.doc.Replace('|', '\|')
        $u = NewH; $su = @(foreach ($x in $s) { if (-not $u.ContainsKey($x)) { $u[$x] = 1; $x } })
        $rows += ('| ' + ('&nbsp;&nbsp;' * $r.depth) + "$($r.id) | $txt | " + ($su -join ', ') + ' | ' + ($v -join ', ') + " | $status |")
    }
    $dd = "$($script:ROOT)/docs"; if (-not (Test-Path -LiteralPath $dd)) { $null = New-Item -ItemType Directory -Path $dd }
    $doc = "$dd/Traceability.md"
    WriteText $doc ("<!-- Generated by: $($script:ME) trace -- do not edit by hand. -->`n`n# $($script:TITLE) Requirements Traceability`n`n" +
        "Each requirement, what satisfies it (inherited from its specification), and which verification`n" +
        "cases verify it. Status: ok, not verified, not satisfied, group (has sub-requirements), need.`n`n" +
        "| ID | Requirement | Satisfied by | Verified by | Status |`n|---|---|---|---|---|`n" + ($rows -join "`n") + "`n")
    $leaves = @($reqs | Where-Object { $_.leaf -and -not ($script:NEED_PREFIX -ne '' -and $_.id.StartsWith($script:NEED_PREFIX)) }).Count
    P ("trace: $($reqs.Count) requirements ($leaves leaf), $missSat not satisfied, $missVer not verified -> " + (Rel $doc) + "`n")
    foreach ($row in $rows) { $m = M $row '\| (?:&nbsp;)*(\S+) \|.*\| (not \w+) \|$'; if ($m.Success) { P "  $($m.Groups[1].Value): $($m.Groups[2].Value)`n" } }
    if (($missSat -or $missVer) -and ($script:ARGS2 -ccontains '--strict')) { 1 } else { 0 }
}

