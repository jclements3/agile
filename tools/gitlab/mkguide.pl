#!/usr/bin/perl
# tools/gitlab/mkguide.pl -- builds docs/GITLAB.html from tools/gitlab/guide.html.in.
#
#   perl tools/gitlab/mkguide.pl [--check]
#
# The guide embeds the templates and the filled-in samples verbatim. A line <!--#include PATH--> (PATH relative to
# tools/gitlab/) is replaced by that file's text, HTML-escaped, inside <pre>. Rerun after changing a template or a
# sample. --check builds in memory and exits 1 if docs/GITLAB.html differs (for a test or a pre-commit hook).
use strict;
use warnings;
use FindBin;

my $here = $FindBin::Bin;
my $out  = "$here/../../docs/GITLAB.html";
my $check = grep { $_ eq '--check' } @ARGV;

sub slurp { my ($p) = @_; open my $fh, '<:raw', $p or die "mkguide: cannot read $p: $!\n"; local $/; my $t = <$fh>; close $fh; $t =~ s/\r\n/\n/g; $t }
sub esc { my ($t) = @_; $t =~ s/&/&amp;/g; $t =~ s/</&lt;/g; $t =~ s/>/&gt;/g; $t }

my $src = slurp("$here/guide.html.in");
my $n = 0;
$src =~ s{^[ \t]*<!--#include ([^>]+?)-->[ \t]*$}{
    my $p = $1; $n++;
    my $t = slurp("$here/$p"); $t =~ s/\n+\z//;
    qq(<pre class="src" title="tools/gitlab/$p"><code>) . esc($t) . "</code></pre>";
}gme;
# <!--#markdown PATH--> renders a wiki page as HTML: ## headings, pipe tables, paragraphs, lists, alerts, inline
# `code`, **bold**, *italic*. The page's own # title and [[_TOC_]] are dropped (the guide has its own).
sub inline { my ($t) = @_; $t = esc($t);
    $t =~ s{`([^`]+)`}{<code>$1</code>}g; $t =~ s{\*\*(.+?)\*\*}{<strong>$1</strong>}g; $t =~ s{(?<![*\w])\*([^*\s][^*]*?)\*(?![*\w])}{<em>$1</em>}g;
    $t =~ s{\[([^\]]+)\]\(([^)]+)\)}{$1}g; $t }
sub markdown {
    my ($md) = @_; my $h = ''; my @l = split /\n/, $md; my $i = 0;
    while ($i < @l) {
        my $l = $l[$i];
        if ($l =~ /^# / || $l =~ /^\[\[_TOC_\]\]/ || $l !~ /\S/) { $i++; next }
        if ($l =~ /^## (.*)/) { $h .= '<h3>' . inline($1) . "</h3>\n"; $i++; next }
        if ($l =~ /^\|/) {
            my @rows; while ($i < @l && $l[$i] =~ /^\|/) { push @rows, $l[$i++] }
            my @c = map { my $r = $_; $r =~ s/^\|\s*//; $r =~ s/\s*\|\s*$//; [ split /\s*\|\s*/, $r, -1 ] } @rows;
            my $head = shift @c; shift @c if @c && $c[0][0] =~ /^:?-+:?$/;
            $h .= "<table>\n<tr>" . join('', map { '<th>' . inline($_) . '</th>' } @$head) . "</tr>\n";
            $h .= '<tr>' . join('', map { '<td>' . inline($_) . '</td>' } @$_) . "</tr>\n" for @c;
            $h .= "</table>\n"; next;
        }
        if ($l =~ /^> /) {
            my @q; while ($i < @l && $l[$i] =~ /^>\s?(.*)/) { push @q, $1; $i++ }
            shift @q if @q && $q[0] =~ /^\[!\w+\]$/;
            $h .= '<div class="note">' . inline(join ' ', @q) . "</div>\n"; next;
        }
        if ($l =~ /^[-*] /) {
            $h .= "<ul>\n"; while ($i < @l && $l[$i] =~ /^[-*] (.*)/) { $h .= '<li>' . inline($1) . "</li>\n"; $i++ } $h .= "</ul>\n"; next;
        }
        my @p; while ($i < @l && $l[$i] =~ /\S/ && $l[$i] !~ /^(#|\||> |[-*] )/) { push @p, $l[$i++] }
        $h .= '<p>' . inline(join ' ', @p) . "</p>\n";
    }
    $h;
}
$src =~ s{^[ \t]*<!--#markdown ([^>]+?)-->[ \t]*$}{ $n++; markdown(slurp("$here/$1")) }gme;
$src =~ s{\A(<!DOCTYPE[^>]*>\n)}{$1<!-- generated by tools/gitlab/mkguide.pl from tools/gitlab/guide.html.in: edit that, not this -->\n} or die "mkguide: guide.html.in must start with <!DOCTYPE html>\n";

if ($check) {
    my $have = -f $out ? slurp($out) : '';
    if ($have ne $src) { print "docs/GITLAB.html is stale: run perl tools/gitlab/mkguide.pl\n"; exit 1 }
    print "docs/GITLAB.html is current ($n includes)\n"; exit 0;
}
open my $fh, '>:raw', $out or die "mkguide: cannot write $out: $!\n";
print $fh $src; close $fh;
print "wrote docs/GITLAB.html ($n includes)\n";
