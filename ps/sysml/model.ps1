    }
    foreach ($x in @('def', 'abstract', 'private', 'public', 'all', 'specializes', 'subsets', 'redefines', 'typed', 'in', 'out', 'inout', 'ref', 'end')) { $n.Remove($x) }
    $f = Join-Path $PSScriptRoot 'sysml-library-names.txt'
