    WriteText $f ("# SysML v2 / KerML standard library names (packages and definitions), extracted from the`n# SysML v2 Pilot implementation's sysml.library (refresh: $($script:ME) libnames DIR).`n# Used by '$($script:ME) lint' to resolve library types offline.`n" + ((@(foreach ($k in $keys) { "$k`n" })) -join ''))
    P "libnames: wrote $($keys.Count) names to $(Rel $f)`n"
    0
}
# ================================================================ views: ps\sysml\views on this project's model/ (job H4)
# Each wrapper runs one tool with the model directory (relative to the current directory) and passes every other
# option through; the exit status is the tool's. The tool's output goes straight to the console, as model.pl's system().
$script:VIEWSDIR = Join-Path $PSScriptRoot 'views'
$script:VIEWRC = 0
function HasOpt([string]$re, $al) { foreach ($x in @($al)) { if ($x -cmatch "^(?:$re)(?:=|\z)") { return $true } }; $false }
function RunView([string]$tool, $al) {
    $p = Join-Path $script:VIEWSDIR $tool
    if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { Flush; PErr "model.pl: $p is missing (the ps\sysml\views toolkit)"; $script:VIEWRC = 2; return }
    Flush
    if ($script:OUTFILE) { $lines = @(& $p @al); $script:VIEWRC = $LASTEXITCODE; foreach ($l in $lines) { P "$l`n" }; return }   # --out: the tool's stdout goes to FILE too
    & $p @al
    $script:VIEWRC = $LASTEXITCODE
}
function CmdView([string]$what) {                                  # call as a statement: the tool's output is not captured
    $al = @($script:ARGS2)
    $mdl = Rel $script:MODEL
    switch -CaseSensitive ($what) {
        'draw' {
            $kind = if ($al.Count) { $al[0] } else { '' }
            $rest = @($al | Select-Object -Skip 1)
            $draw = @{ tree = @('sysml-tree-svg.ps1', 'part decomposition'); trace = @('sysml-trace-svg.ps1', 'requirement trace'); ibd = @('sysml-ibd-svg.ps1', 'interconnection and trust zones'); pkg = @('sysml-pkg-svg.ps1', 'packages and markings') }
            if ($kind -cnotmatch '^(tree|trace|ibd|pkg)$') { Flush; PErr "usage: $($script:ME) draw tree|trace|ibd|pkg [-o FILE] [tool options]"; $script:VIEWRC = 2; return }
            $d = $draw[$kind]
            $a2 = $rest
            if (-not (HasOpt '-o|--o' $a2)) { $a2 = @('-o', "$kind.svg") + $a2 }
            if ($kind -ceq 'pkg' -and -not (HasOpt '--no-markings' $a2)) {
                $marked = $false; foreach ($f in $script:FILES) { if ($script:RAWS[$f] -cmatch '@Marking\b') { $marked = $true; break } }
                if (-not $marked) { $a2 = @('--no-markings') + $a2; P "draw pkg: no @Marking in the model, so markings are not checked (the gate still checks them)`n" }
            }
            if (-not (HasOpt '--title' $a2)) {
                $desc = if ($kind -ceq 'pkg' -and (HasOpt '--no-markings' $a2)) { 'packages and dependencies' } else { $d[1] }
                $a2 = @('--title', "$($script:TITLE): $desc") + $a2
            }
            RunView $d[0] ($a2 + @($mdl))
        }
        'plates' { $a2 = $al; if (-not (HasOpt '-o|--o' $a2)) { $a2 = @('-o', 'plates') + $a2 }; RunView 'sysml-plates.ps1' ($a2 + @($mdl)) }
        'diff' {
            $pos = @(); $git = $false
            for ($i = 0; $i -lt $al.Count; $i++) {
                if ($al[$i] -cmatch '^(?:-o|--o|--root|--git|--today)\z') { if ($al[$i] -ceq '--git') { $git = $true }; $i++ }
                elseif ($al[$i] -cnotmatch '^-') { $pos += , $al[$i] }
            }
            $a2 = $al
            if ($git) { if (-not $pos.Count) { $a2 += , $mdl } } elseif ($pos.Count -eq 1) { $a2 += , $mdl }
            RunView 'sysml-diff.ps1' $a2
        }
        'threats' { RunView 'sysml-threats.ps1' ($al + @($mdl)) }
        'gate' { RunView 'sysml-check.ps1' (@('--tools', (Join-Path $script:VIEWSDIR 'binder')) + $al + @($mdl)) }
    }
}

