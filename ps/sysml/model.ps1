        $ms = MS $n "($($script:ALT))"
        if ($ms.Count) {
            $parts = @(); $at = 0
            foreach ($m in $ms) {
                $parts += $n.Substring($at, $m.Index - $at)
                $v = $m.Groups[1].Value
                $tok += $(if ($script:SPELL.ContainsKey($v)) { $script:SPELL[$v] } else { $v })
