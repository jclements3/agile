function Report {
    $mm = TagMismatches
    P ("`n== Level tags ==`n@L tag mismatches         $($mm.Count)`n")
    foreach ($x in $mm) { P ("  $($x[0]): tagged L$(LevelOf $x[0]), first reached at L$($x[1])`n") }
    $bad = Outline
    P ("`n== Outline ($($script:MIN)..$($script:MAX) children per parent) ==`nviolations                $($bad.Count)`n")
    $sorted = SortBy $bad { param($x, $y) $r = Cmp $x[0] $y[0]; if ($r) { return $r }; Cmp $x[1] $y[1] }
    foreach ($x in $sorted) { P ('  ' + (PadL $x[2] 3) + "  $($x[1])  ($($x[0]))`n") }
    if ($script:OPT.quickfix -and ($mm.Count -or $bad.Count)) {
        P "`n"
        foreach ($x in $mm) { $d = $script:DEFS[$x[0]]; P ((Rel $d.file) + ":$($d.line): error: $($x[0]) tagged L$(LevelOf $x[0]), first reached at L$($x[1])`n") }
        foreach ($x in $sorted) {
            $pre = if ($x[0] -cmatch '/\z') { "$($x[0]) " } else { '' }
            P ((Rel $x[3]) + ":$($x[4]): error: $pre$($x[1]): $($x[2]) (outside $($script:MIN)..$($script:MAX))`n")
        }
    }
    if ($mm.Count -or $bad.Count) { 1 } else { 0 }
}

