    if ($isVerb -and $null -ne $d -and $d.returns) {
        $r = if ($script:OPT.plain) { PlainName $d.returns } else { $d.returns }
        if ($script:OPT.plain -and $script:FRIENDLY.ContainsKey($r)) { $r = $script:FRIENDLY[$r] }
        $lst = if ($d.many) { "list of $r" } else { $r }
        if (-not $script:OPT.ascii) { $s += "  $($script:RARR) $lst" }
        if ($script:OPT.ascii) { $s += "  -> $lst" }
    }
    $s
}
function TreeWalk([string]$n, [string]$prefix, [bool]$last, [bool]$isRoot, [bool]$isVerb) {
    $g = $script:TG
    $kids = @(); $u = NewH
    foreach ($kv in (Children $n)) { if ($script:DEFS.ContainsKey($kv[1]) -and -not $u.ContainsKey($kv[1])) { $u[$kv[1]] = 1; $kids += $kv[1] } }
    $repeat = $script:EXPANDED.ContainsKey($n) -and $kids.Count
    $lead = if ($isRoot) { '' } else { $prefix + $(if ($last) { $g[1] } else { $g[0] }) }
    $script:TL += , ($lead + (Label $n $isVerb) + $(if ($repeat) { $g[4] } else { '' }))
    if ($repeat) { return }
    $script:EXPANDED[$n] = 1
    $p = if ($isRoot) { '' } else { $prefix + $(if ($last) { $g[3] } else { $g[2] }) }
    for ($i = 0; $i -lt $kids.Count; $i++) { TreeWalk $kids[$i] $p ($i -eq $kids.Count - 1) $false $isVerb }
}
function TreeLines([string]$rootName, [bool]$isVerb) {
    $script:TG = Glyphs; $script:EXPANDED = NewH; $script:TL = @()
    TreeWalk $rootName '' $true $true $isVerb
    , $script:TL
}
function DWalk([string]$n, [int]$depth, $path) {
    foreach ($x in $path) { if ($x -ceq $n) { return } }
    $path = @($path) + $n
    if (-not $script:DW_FIRST.ContainsKey($n) -or $depth -lt $script:DW_FIRST[$n]) { $script:DW_FIRST[$n] = $depth }
    if ($path.Count -gt $script:DW_LONG.Count) { $script:DW_LONG = $path }
    $subs = $script:SUBCLASSES[$n]; if ($null -eq $subs) { $subs = @() }
    $pre = @(for ($i = 0; $i -lt $path.Count - 1; $i++) { $path[$i] })
    foreach ($s in $subs) { DWalk $s $depth $pre }
    foreach ($kv in (Children $n)) { if ($script:DEFS.ContainsKey($kv[1])) { DWalk $kv[1] ($depth + 1) $path } }
}
function DepthWalk([string]$rootName) {                                 # @(first-depth hashtable, longest chain)
    $script:DW_FIRST = NewH; $script:DW_LONG = @()
    DWalk $rootName 1 @()
    , @($script:DW_FIRST, $script:DW_LONG)
}

