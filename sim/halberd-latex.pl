# halberd-latex.pl -- docs/HALBERD.tex for sim/halberd-gen.pl (required from there, not run on its own).
# The same content as docs/HALBERD.html, typeset for print: black and white, booktabs tables, pgfplots charts
# (solid / dashed / dotted lines and grey bars, never colour). Build the PDF with `perl sim/halberd-gen.pl --pdf`
# (needs XeLaTeX + latexmk; the kit's target laptop has neither, so docs/HALBERD.pdf is committed).
use strict;
use warnings;
use List::Util ();

sub _lx_tx {                                      # plain text -> LaTeX
    my $t = shift // '';
    $t =~ s/\\/\x01/g;
    $t =~ s/([&%\$#_{}])/\\$1/g;
    $t =~ s/~/\\textasciitilde{}/g;
    $t =~ s/\^/\\textasciicircum{}/g;
    $t =~ s/\x01/\\textbackslash{}/g;
    $t =~ s/(\d)--(\d)/$1--$2/g;
    $t =~ s/\.\.\./\\ldots{}/g;
    $t;
}
sub _lx_md { my $t = _lx_tx(shift); $t =~ s/\*\*(.+?)\*\*/\\textbf{$1}/g; $t }   # the doc's cells use **bold** only
sub _lx_c  { my $n = shift; 1 while $n =~ s/^(-?\d+)(\d{3})/$1,$2/; $n }
sub _lx_usd { my $v = sprintf '%.0f', shift; my $neg = $v < 0; $v = abs $v; 1 while $v =~ s/^(\d+)(\d{3})/$1,$2/; ($neg ? '$-$' : '') . "\\\$$v" }
sub _lx_date { my ($y, $m, $d) = split /-/, shift; my @mn = qw(January February March April May June July August September October November December); sprintf '%d %s %d', $d, $mn[ $m - 1 ], $y }

sub _lx_plot_lines {                              # [ [legend, style, [values]] ], x tick labels
    my ($labels, $series, %o) = @_;
    my $n = @$labels;
    my $ticks = join ',', grep { $_ % 2 == 0 || $_ == $n - 1 } 0 .. $n - 1;
    my $tl = join ',', map { "{$labels->[$_]}" } grep { $_ % 2 == 0 || $_ == $n - 1 } 0 .. $n - 1;
    my $s = "\\begin{tikzpicture}\n\\begin{axis}[halberdplot, width=$o{width}, height=$o{height}, xtick={$ticks}, xticklabels={$tl}"
          . ($o{ylabel} ? ", ylabel={$o{ylabel}}" : '') . ($o{money} ? ', scaled y ticks=false, yticklabel style={/pgf/number format/.cd, fixed, precision=0, 1000 sep={\\mbox{,}}}, ymin=0, yticklabel={\\$\\pgfmathprintnumber{\\tick}}' : '')
          . ", legend columns=" . scalar(@$series) . "]\n";
    for my $sr (@$series) {
        my ($name, $style, $v) = @$sr;
        $s .= "\\addplot[$style] coordinates {" . join(' ', map { sprintf '(%d,%.1f)', $_, $v->[$_] } 0 .. $#$v) . "};\n\\addlegendentry{$name}\n";
    }
    "$s\\end{axis}\n\\end{tikzpicture}\n";
}

sub halberd_latex {
    my ($file, %a) = @_;
    my ($days, $sprints, $plan, $seg, $rows, $es) = @a{qw(days sprints plan seg journal_rows evm_series)};
    my @order = qw(E V B T G M L);
    my (%seg_pts, %seg_tasks, %first, %last);
    for my $p (@$plan) { for my $t (@{ $p->{tasks} }) { $seg_pts{ $t->{seg} } += $t->{pts}; $seg_tasks{ $t->{seg} }++ } }
    for my $d (@$days) { $first{ $d->{seg} } //= $d->{date}; $last{ $d->{seg} } = $d->{date} }
    my @left = (1960); push @left, $left[-1] - $_->{done} for @$sprints;

    my $o = <<'PRE';
% Generated by sim/halberd-gen.pl (sim/halberd-latex.pl). Edit the doc or the generator, not this file.
% Build: perl sim/halberd-gen.pl --pdf   (XeLaTeX + latexmk)
\documentclass[12pt,letterpaper,oneside]{article}
\usepackage[margin=1in,headheight=14pt]{geometry}
\usepackage{fontspec}
\setmainfont{LibertinusSerif}[Extension=.otf,UprightFont=*-Regular,BoldFont=*-Bold,ItalicFont=*-Italic,BoldItalicFont=*-BoldItalic]
\setsansfont{LibertinusSans}[Extension=.otf,UprightFont=*-Regular,BoldFont=*-Bold,ItalicFont=*-Italic,BoldItalicFont=*-Bold]
\setmonofont{DejaVu Sans Mono}[Scale=0.80]
\usepackage{microtype}
\usepackage{booktabs,longtable,array,tabularx}
\usepackage{xcolor}
\usepackage{pgfplots}
\pgfplotsset{compat=1.17}
