            $k = $m.Groups[1].Value
            $kk = if ($k -ceq 'part') { 'd' } elseif ($k -ceq 'calc' -or $k -ceq 'action') { 'f' } else { $k.Substring(0, 1) }
            & $add $m.Groups[2].Value $m.Groups[2].Index $kk
        }
        foreach ($m in (MS $raw "\brequirement\s+<'([^']+)'>")) { & $add $m.Groups[1].Value $m.Groups[1].Index 'r' }
        foreach ($m in (MS $t '\brequirement\s+(?!def\b)(\w+)\s*[{:;]')) { & $add $m.Groups[1].Value $m.Groups[1].Index 'r' }
