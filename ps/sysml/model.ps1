        $t = $script:MASKS[$f]; $raw = $script:RAWS[$f]; $r = RelRoot $f
        $add = { param($name, $pos, $kind) $l = (LineColM $raw $pos)[0]; $script:TAGS += "$name`t$r`t$l;`"`t$kind" }
